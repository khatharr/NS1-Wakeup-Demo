/**
 * @brief Calculate the access code and wake-up code from a Bluetooth address
 *
 * @note
 * - The access code used to wake the Switch inverts the lower 32 bits of the standard BR/EDR access code.
 * - Append a six-bit Barker sequence to the last three Bluetooth address bytes (24-bit LAP), encode the resulting 30 bits with a shortened (64,30) BCH code, and XOR a 64-bit PN sequence.
 * - The upper three address bytes do not affect the result if LAP is unchanged.
 */
#ifndef WAKEUP_CODE_H
#define WAKEUP_CODE_H

#include <stdint.h>

/**
 * @brief Return the 64-bit portion of the BR/EDR access code for a Bluetooth address
 * @param address Bluetooth address
 * @return 64-bit portion of the access code
 */
uint64_t switch1_sync_word(const uint8_t address[6]);

/**
 * @brief Return the lower 34-bit BCH parity portion of a 64-bit value
 * @param address Bluetooth address
 * @return BCH parity portion
 * @note Writing this into the CSB control structure causes hardware to assemble the 72-bit access code.
 */
uint64_t switch1_parity34(const uint8_t address[6]);

/**
 * @brief Return the access-code parity used for wake-up
 * @param address Bluetooth address
 * @return Parity from switch1_parity34() with the low 32 bits inverted
 */
uint64_t switch1_wakeup_parity34(const uint8_t address[6]);

/**
 * @brief Generate the four bytes repeated in the Phase 1 payload
 * @param address Bluetooth address
 * @param[out] out Buffer to receive the four generated bytes in least-significant-byte-first order
 * @note Value formed by inverting the low 32 bits of the 64-bit value; its over-the-air order matches the low 32 bits of the wake-up access code.
 */
void switch1_wakeup_code(const uint8_t address[6], uint8_t out[4]);

/**
 * @brief Convert a Bluetooth address to least-significant-byte-first order for the transmit buffer
 * @param address esp_bd_addr_t address in most-significant-byte-first order
 * @param[out] out Buffer to receive the six converted bytes
 */
void switch1_bd_addr_lsb_first(const uint8_t address[6], uint8_t out[6]);

/**
 * @brief Build a BR/EDR payload header
 * @param length Payload length in bytes
 * @param flow Bit value for the FLOW field
 * @param llid Bit value for the LLID field
 * @return Payload header with length, FLOW, and LLID in the designated positions
 */
uint16_t switch1_txphdr(uint8_t length, uint8_t flow, uint8_t llid);

#endif
