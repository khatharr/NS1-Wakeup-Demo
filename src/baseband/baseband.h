#ifndef BASEBAND_H
#define BASEBAND_H

#include <stdbool.h>
#include <stdint.h>

#include "esp_err.h"

/**
 * @brief Maximum CSB payload body length
 * @note Fits one DH5 packet (339 bytes) containing repeated wake-up codes
 */
#define SWITCH1_CSB_DATA_MAX 339

/**
 * @brief Transmit a payload body over CSB without applying whitening
 * @param bd_addr Peer BD_ADDR
 * @param bch34 BCH parity for wake-up
 * @param data Payload body before whitening
 * @param length Length of data
 * @param interval Transmit interval specified in slots
 * @param channel Channel to use
 * @note Use the following values for channel:
 * - 0: 2402MHz
 * - 24: 2426MHz
 * The controller generates the packet and payload headers.
 */
esp_err_t switch1_csb_raw_start(const uint8_t bd_addr[6], uint64_t bch34,
                                const uint8_t *data, uint16_t length,
                                uint16_t interval, uint8_t channel);

/**
 * @brief Update the wake-up parity and channel in the descriptor generated by ROM
 * @note Without this update, the access code uses its normal value.
 * Call before transmitting each burst.
 */
esp_err_t switch1_csb_wake_refresh(void);

/**
 * @brief Wait for CSB transmission to stop
 * @note The wait is limited to 8 seconds, as in the HCI layer.
 */
esp_err_t switch1_csb_wake_stop_wait(void);

uint32_t switch1_csb_wake_events(void);

/**
 * @brief Return the location of the transmit descriptor
 * @return Returns 0 if no descriptor has been created
 */
uint16_t switch1_csb_descriptor_offset(void);

/**
 * @brief Return the location of the payload region referenced by the current descriptor
 * @return Returns 0 if the location cannot be obtained
 * @note No descriptor exists between bursts; save the location obtained during transmission for later use.
 */
uint16_t switch1_csb_payload_offset(void);

/**
 * @brief Write directly to the transmit payload at the specified location
 * @param payload_offset Offset of the payload region
 * @param data Data to write
 * @param length Length of data
 * @note Can write to the saved location between bursts, even without a descriptor.
 */
esp_err_t switch1_csb_write_payload_at(uint16_t payload_offset,
                                       const uint8_t *data, uint16_t length);

esp_err_t switch1_csb_read_descriptor(uint16_t *out_header,
                                      uint16_t *out_pheader);

esp_err_t switch1_csb_write_descriptor(uint16_t header, uint16_t pheader);

/**
 * @brief Set the transmit position as an offset from the slot boundary
 * @param offset_us Position from 0 to 1023 us
 * @note Write both control structure +0x02 and schedule element +0x14.
 * Transmission timestamps advance in 625 us steps, but writing both fields permits positioning with 1 us resolution.
 */
esp_err_t switch1_csb_tx_set_bit_offset(uint16_t offset_us);

/**
 * @brief Update the scheduled transmission duration of the transmit schedule element
 * @param duration_us Transmission duration registered with the scheduler, in us
 * @note If left at ESP-IDF's 9255 us, the transmit period becomes 15 ms to avoid a scheduling conflict with CSB reception.
 * Set the transmit event duration to 1875 us.
 */
esp_err_t switch1_csb_tx_set_duration(uint16_t duration_us);

/**
 * @brief Enable or disable transmit whitening
 * @param disable true disables whitening
 * @note Manipulates bit 12 at control structure +0x08.
 * When disabled, perform the following:
 * - Do not whiten the payload body or payload header.
 * - Write the unwhitened content into the payload.
 */
void switch1_csb_tx_set_whitening_disable(bool disable);

/**
 * @brief Override the transmit frame format
 * @param format Frame format to write to bits 0-4 at control structure +0x00
 * @param[out] out_before Unless NULL, receives the word before modification
 * @return Returns ESP_OK on success
 * @note The default format is 24 (CSB transmission).
 */
esp_err_t switch1_csb_tx_set_frame_format(uint8_t format, uint16_t *out_before);

bool switch1_csb_tx_read_schedule(uint32_t *out_next_slot,
                                  uint16_t *out_interval);

/**
 * @brief Reschedule a pending transmit event to the requested position
 * @param target_slot Transmit slot
 * @param bit_offset_us Position within the slot, in us
 * @param minimum_ahead_slots Minimum number of slots ahead of the current time
 * @param[out] out_scheduled_slot Returns the slot actually scheduled
 * @note If the requested position is too close, add the current transmit period to move to the same phase.
 */
esp_err_t switch1_csb_tx_reschedule(uint32_t target_slot,
                                    uint16_t bit_offset_us,
                                    uint16_t minimum_ahead_slots,
                                    uint32_t *out_scheduled_slot);

/**
 * @brief Change the transmit period
 * @param expect Expected current period
 * @param interval New period in slots
 * @return Returns ESP_ERR_INVALID_STATE if expect does not equal the current value
 * @note Resolution is one slot (625 us).
 * Changing the period once affects the interval for that transmission.
 * The same offset carries forward to later transmissions, allowing adjustment of Phase 3 timing.
 */
esp_err_t switch1_csb_tx_set_interval(uint16_t expect, uint16_t interval);

/**
 * @brief Start CSB reception
 * @param bd_addr Peer BD_ADDR
 * @param bch34 BCH parity for wake-up
 * @param interval Receive-attempt interval in slots
 * Must be even
 * @param clock_offset Clock offset configured for the receiver
 * @param next_clock Clock for the next receive attempt
 * @param channel Receive channel
 * @return Returns the HCI command result
 * @note After sending HCI Set_Connectionless_Slave_Broadcast_Receive (0x0442), write wake-up parity to the receiver control structure.
 */
esp_err_t switch1_csb_rx_start(const uint8_t bd_addr[6], uint64_t bch34,
                               uint16_t interval, uint32_t clock_offset,
                               uint32_t next_clock, uint8_t channel);

/**
 * @brief Re-register a receive schedule element released by the supervision timeout
 * @param interval Receive-attempt interval in slots
 * @param next_clock Clock for the next receive attempt
 * @return Returns the HCI command result
 * @note ld_csb_rx_env remains after the element is freed, so a start request alone makes r_ld_csb_rx_start return 12 (Command Disallowed).
 * Send a stop request before requesting a start.
 */
esp_err_t switch1_csb_rx_restart(uint16_t interval, uint32_t next_clock);

esp_err_t switch1_csb_rx_stop(const uint8_t bd_addr[6], uint16_t interval);

/**
 * @brief Return whether CSB reception is active
 * @return Returns true if reception is running, including when a stop request was rejected and reception continues
 */
bool switch1_csb_rx_is_active(void);

/**
 * @brief Retrieve the latest received CSB packet
 * @param[out] out_addr Returns the source BD_ADDR
 * @param[out] out_clock Returns the receive clock
 * @param[out] out_status Returns the receive status
 * @param[out] out_data Returns the received data
 * @param[out] out_length Returns the received-data length
 * @return Returns false when no received data is available
 * @note Release the held packet after retrieval.
 */
bool switch1_csb_rx_take(uint8_t out_addr[6], uint32_t *out_clock,
                         uint8_t *out_status, uint8_t *out_data,
                         uint8_t *out_length);

/**
 * @brief Read the most recent hardware-measured receive timestamp
 * @param[out] out_clk Returns the receive clock in slots
 * @param[out] out_bitoff Returns the offset within the slot in us
 * Range is 0 to 624 us
 * @param[out] out_raw Returns the uncorrected value
 * @return Returns false if the high word is out of range
 */
bool switch1_csb_rx_read_sync(uint32_t *out_clk, uint16_t *out_bitoff,
                              uint16_t *out_raw);

/**
 * @brief Override LT_ADDR in the receiver control structure
 * @param lt_addr LT_ADDR written into bits 10:8 at +0x08
 * @note The Switch response uses LT_ADDR 0, but the HCI command accepts only 1-7.
 */
void switch1_csb_rx_write_ltaddr(uint8_t lt_addr);

/**
 * @brief Override the receive frame format
 * @param format Frame format written to bits 0-4 at control structure +0x00
 * @note Default is 25.
 * Use the following values for ACL formats:
 * - 2 or 3: hardware stores the received payload in the buffer.
 */
void switch1_csb_rx_set_format(uint8_t format);

esp_err_t switch1_csb_rx_dump(uint16_t offset, uint8_t count, uint16_t *out);

/**
 * @brief Return the number of successful receptions
 * @return Returns the number of receptions
 * @note Count HCI events 0x51 with Receive_Status equal to 0.
 * Consecutive successes leave the receive descriptor status unchanged, so reception count cannot be derived from status changes.
 */
uint32_t switch1_csb_rx_event_count(void);

void switch1_csb_rx_event_reset(void);

/**
 * @brief Examine the receive descriptor once and return a reception without failure flags
 * @param[out] out_status Returns the receive descriptor status
 * @param[out] out_header Returns the received packet header
 * @param[out] out_pheader Returns the received payload header
 * @return Returns true if the descriptor status changed, is nonzero, and has no failure flags
 * @note Does not wait, so it can be called during transmission.
 * Used to align Phase 3 transmission with the Switch response timing.
 */
bool switch1_csb_rx_poll(uint16_t *out_status, uint16_t *out_header,
                         uint16_t *out_pheader);

/**
 * @brief Save the status and level of four receive descriptors as a baseline and clear status statistics
 * @note Call before monitoring so already-present receptions are excluded.
 */
void switch1_csb_rx_poll_prime(void);

/**
 * @brief Log the types and counts of statuses collected by switch1_csb_rx_poll
 * @note When zero packets are received, distinguish lack of synchronization from rejection during validation after synchronization.
 */
void switch1_csb_rx_poll_report(void);

/**
 * @brief Monitor receive descriptors for the specified duration and log any that change
 * @param duration_ms Monitoring duration in ms
 * @return Returns the number of detected changes
 * @note Reads the four descriptors watched by ld_csb_rx_frm_cbk directly, allowing reception checks even without HCI events.
 */
uint32_t switch1_csb_rx_watch(uint32_t duration_ms);

/**
 * @brief Store the transmit and receive schedule elements
 * @note Transmission and reception share the same radio-event scheduler.
 * - r_ea_elt_insert compares priority at element +0x16 and rejects a new element if an existing element has equal or higher priority.
 * - Receive priority starts at 10 and increases by 1 after each failure.
 * - Transmit priority resets to 10 after each frame completes.
 * - When receive priority reaches 11, transmission can no longer be scheduled.
 */
typedef struct {
    /** Address of the schedule element itself; 0 means the element was freed and CSB is stopped. */
    uint32_t tx_element;
    uint32_t rx_element;
    /** Transmit duration registered with the scheduler at +0x12, in us. */
    uint16_t tx_duration_us;
    uint16_t rx_duration_us;
    /** Priority stored at +0x16. */
    uint8_t tx_priority;
    uint8_t rx_priority;
    /** Receive interval at +0x36, in slots. The transmit period is at +0x30; for a receive element, +0x30 is the clock offset. */
    uint16_t rx_interval_slots;
    /**
     * Stores the receiver state at +0x3E.
     * - 0: stopped
     * - 1: running
     * - 2: stop request pending
     */
    uint8_t rx_state;
    /**
     * Stores the reference clock for the receive supervision timeout at +0x2C and the supervision timeout at +0x3A.
     * ld_csb_rx_sched (0x400391f0) compares elapsed time and frees the element when the timeout expires.
     */
    uint32_t rx_sup_base;
    uint16_t rx_sup_timeout_slots;
} switch1_csb_sched_t;

/**
 * @brief Read the transmit and receive schedule elements
 * @param[out] out Returns the retrieved schedule elements
 * @note Read only; do not write to schedule elements.
 */
void switch1_csb_sched_read(switch1_csb_sched_t *out);

/**
 * @brief Prepare to capture the 17-byte response before the CSB receive callback releases the descriptor
 * @param bd_addr Peer BD_ADDR
 * @param bch34 BCH parity for wake-up
 * @return Returns the preparation result
 * @note On success, obtains the relative Switch/ESP32 clock delta and LT_ADDR for the next ACL link.
 */
esp_err_t switch1_phase2_capture_start(const uint8_t bd_addr[6], uint64_t bch34);
bool switch1_phase2_capture_take(esp_err_t *out_result, uint8_t *out_lt_addr,
                                 uint32_t *out_clock_delta,
                                 uint32_t *out_rx_clk,
                                 uint16_t *out_rx_bitoff);
void switch1_phase2_capture_cancel(void);

/**
 * @brief Output the captured body and receiver control structure over UART
 * @note Separate from switch1_phase2_capture_take.
 * At 115200 bps, printing one line takes approximately 10 ms.
 * This would delay Phase 3 after capture, so call only after Phase 3 has been transmitted.
 */
void switch1_phase2_capture_report(void);

/**
 * @brief Register an ACL receive event using frame format 3 immediately after the Switch response
 * @param bd_addr Peer BD_ADDR
 * @param bch34 BCH parity for wake-up
 * @param lt_addr LT_ADDR for the ACL link
 * @param clock_delta Relative clock difference between the Switch and ESP32
 * @param rx_clk Clock when the Switch response was received
 * @param rx_bitoff Within-slot offset of the Switch response in us
 * @param phase3_slot Slot in which Phase 3 was transmitted
 * @return Returns the ACL receive-event registration result
 * @note On successful reception, the callback begins the same ACL link procedure used by paging.
 */
esp_err_t switch1_acl_handoff_start(const uint8_t bd_addr[6], uint64_t bch34,
                                    uint8_t lt_addr, uint32_t clock_delta,
                                    uint32_t rx_clk, uint16_t rx_bitoff,
                                    uint32_t phase3_slot);
bool switch1_acl_handoff_status(esp_err_t *out_result, uint8_t *out_link_id);

/**
 * @brief Report whether r_lc_start was called and the state after the call
 * @param[out] out_lc_state lc_state[link_id] after r_lc_start
 * @note On an ACL link where the ESP32 acts as Bluetooth peripheral, lc_state[link_id] becomes LC_STATE_PERIPHERAL_IDLE (5) after r_lc_start.
 * @param[out] out_flags Returns the following state flags as bits
 * - bit0: lc_env
 * - bit1: ld_acl_env
 * - bit2: llc_env
 * - bit 3: BD_ADDR registered in hci_env
 * @return Returns true if the state could be retrieved
 */
bool switch1_lc_start_status(uint8_t *out_lc_state, uint8_t *out_flags);

/**
 * @brief Disconnect a wake-up-created ACL link from the controller side
 * @return Returns the disconnect-request result
 * @note Used to reconnect via normal paging after the Switch screen turns on.
 * While ACL occupies link 0, paging is rejected with ACL Connection Already Exists.
 * Reason code is 0x13 (Remote User Terminated).
 */
esp_err_t switch1_acl_detach(void);

/**
 * @brief Return the internal state of the link created by wake-up
 * @return Returns 0xff if no link exists
 */
uint8_t switch1_acl_lc_state(void);

/**
 * @brief Change lc_state[link_id] to LC_STATE_PERIPHERAL_IDLE (5) from a state that rejects disconnect requests
 * @return Returns the transition result
 * @note LC_STATE_PERIPHERAL_IDLE (5) accepts disconnect requests.
 */
esp_err_t switch1_acl_force_idle(void);

/**
 * @brief Release the ESP32-side link without waiting for disconnection to complete
 * @return Returns the release result
 */
esp_err_t switch1_acl_release(void);

/**
 * @brief Read the native clock CLKN from the Bluetooth core registers
 * @param[out] out_clkn Returns a 28-bit value in units of 312.5 us
 * @return true if the read succeeds
 * false if sampling could not finish.
 * @note Requires no HCI communication, so it can be called while processing each burst.
 */
bool switch1_csb_read_clkn(uint32_t *out_clkn);

/**
 * @brief Allow the next HCI Create Connection once and pass Clock_Offset
 * @param bd_addr Peer BD_ADDR
 * @param offset Clock_Offset to apply
 * Keep the default if 0.
 */
void switch1_hci_clock_offset_set(const uint8_t bd_addr[6], uint16_t offset);
void switch1_hci_page_cancel(void);

/**
 * @brief Enable or disable detailed state output
 * @param enabled true enables output
 * @note Enabled by default.
 * Disable during connection cycles because detailed logging delays processing from link establishment through reconnection.
 */
void switch1_set_report_verbose(bool enabled);

#endif
